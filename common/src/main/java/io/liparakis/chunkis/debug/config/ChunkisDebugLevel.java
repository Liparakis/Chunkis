package io.liparakis.chunkis.debug.config;

public enum ChunkisDebugLevel {
    /**
     * Stores off.
     */
    OFF,
    /**
     * Stores errors only.
     */
    ERRORS_ONLY,
    /**
     * Stores lifecycle.
     */
    LIFECYCLE,
    /**
     * Stores verbose.
     */
    VERBOSE,
    /**
     * Represents this debug level.
     */
    PARANOID
}
